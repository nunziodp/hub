// Andamento performance 30gg per RDV (tab Performance) — serie deterministica
// di lead consegnate giornaliere, parametrizzata per RDV.
export function generaPerformanceRdv(rdvId, base = 6) {
  const seed = rdvId === 'rdv-001' ? 9 : rdvId === 'rdv-002' ? 5 : 3
  const punti = []
  const oggi = new Date()
  for (let i = 29; i >= 0; i--) {
    const data = new Date(oggi)
    data.setDate(oggi.getDate() - i)
    const gs = data.getDay()
    const fattoreGiorno = gs === 0 || gs === 6 ? 0.6 : 1
    const noise = 0.7 + ((data.getDate() * (seed + 7)) % 30) / 50
    punti.push({
      data: data.toISOString().slice(0, 10),
      consegnate: Math.max(0, Math.round((base + seed) * fattoreGiorno * noise)),
    })
  }
  return punti
}

