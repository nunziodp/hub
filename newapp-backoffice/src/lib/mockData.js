// Helper: costruisce un campaign_name_raw nel formato definito in 10.1
function buildCampaignName({
  id, child, settore, cliente, campagna, offerta, creativita, formato, fonte, versione, automazione,
}) {
  const idFull = child ? `${id}.${child}` : id
  return [idFull, settore, cliente, campagna, offerta, creativita, formato, fonte, versione, automazione]
    .map(v => v ?? '-')
    .join(' | ')
}

