// Genera 14 punti giornalieri di volume (ricevute/distribuite) con un trend
// realistico ma deterministico, ancorato a "oggi". Usato dal VolumeChart.
function generaVolume14gg() {
  const punti = []
  const oggi = new Date()
  for (let i = 13; i >= 0; i--) {
    const data = new Date(oggi)
    data.setDate(oggi.getDate() - i)
    // Pattern: weekend ~30% in meno, leggero trend in crescita verso oggi
    const giornoSettimana = data.getDay()
    const fattoreGiorno = giornoSettimana === 0 || giornoSettimana === 6 ? 0.7 : 1
    const fattoreTrend = 1 + (13 - i) * 0.012
    // Componente deterministica pseudo-random basata sul giorno del mese
    const noise = 0.85 + ((data.getDate() * 37) % 30) / 100
    const ricevute = Math.round(310 * fattoreGiorno * fattoreTrend * noise)
    // Tasso distribuzione 70-85%
    const tassoDistr = 0.72 + ((data.getDate() * 53) % 13) / 100
    const distribuite = Math.round(ricevute * tassoDistr)
    punti.push({
      data: data.toISOString().slice(0, 10),
      ricevute,
      distribuite,
    })
  }
  return punti
}

